"""Prepare explicit OCR derivatives for a local domain trial, never application OCR.

Original files remain unchanged. The transparent text layer is generated by the
local Windows OCR engine. Pages must render identically after any explicitly
declared orientation correction; original files are never rotated in place.
"""
import argparse
import asyncio
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

import fitz


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write(path, value):
    path.write_bytes((json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8"))


def inspect(path):
    with fitz.open(path) as pdf:
        rows = [{"pdf_page": i + 1, "characters": len(p.get_text().strip()),
                 "has_images": bool(p.get_images())} for i, p in enumerate(pdf)]
    return rows


async def ocr_derivative(source, target, rows, rotation=0):
    from winrt.windows.globalization import Language
    from winrt.windows.media.ocr import OcrEngine
    from winrt.windows.graphics.imaging import BitmapDecoder
    from winrt.windows.storage.streams import DataWriter, InMemoryRandomAccessStream

    engine = OcrEngine.try_create_from_language(Language("en-US"))
    if engine is None:
        raise RuntimeError("Windows English OCR is not available")
    reports = []
    font = fitz.Font(fontfile="C:/Windows/Fonts/arial.ttf")
    with fitz.open(source) as pdf:
        for row in rows:
            if row["characters"] >= 80 or not row["has_images"]:
                continue
            page = pdf[row["pdf_page"] - 1]
            if rotation:
                page.set_rotation((page.rotation + rotation) % 360)
                page.remove_rotation()
            scale = min(3, 2500 / max(page.rect.width, page.rect.height))
            pixels = page.get_pixmap(matrix=fitz.Matrix(scale, scale), alpha=False)
            with InMemoryRandomAccessStream() as stream:
                writer = DataWriter(stream)
                writer.write_bytes(pixels.tobytes("png"))
                await writer.store_async()
                stream.seek(0)
                decoder = await BitmapDecoder.create_async(stream)
                bitmap = await decoder.get_software_bitmap_async()
                recognized = await engine.recognize_async(bitmap)
            page.insert_font(fontname="ocrtrial", fontfile="C:/Windows/Fonts/arial.ttf")
            words = 0
            for line in recognized.lines:
                for word in line.words:
                    rect = word.bounding_rect
                    box = fitz.Rect(rect.x / scale, rect.y / scale,
                                    (rect.x + rect.width) / scale, (rect.y + rect.height) / scale)
                    if not word.text.strip() or box.is_empty:
                        continue
                    size = max(3, min(18, box.height * .78))
                    # Fit the word width as well as its height, keep it invisible.
                    width = font.text_length(word.text, fontsize=size)
                    if width > box.width:
                        size *= box.width / width
                    page.insert_text((box.x0, min(page.rect.height - 1, box.y1)), word.text,
                                     fontsize=size, fontname="ocrtrial", render_mode=3)
                    words += 1
            reports.append({"pdf_page": row["pdf_page"], "ocr_words": words})
            print(source.stem + ": OCR page " + str(row["pdf_page"]) + ", words=" + str(words), flush=True)
        pdf.save(target, garbage=3, deflate=True)
    # Invisible text must not change the original visible pages.
    with fitz.open(source) as original, fitz.open(target) as derived:
        if len(original) != len(derived):
            raise ValueError("OCR changed page count")
        for row in reports:
            n = row["pdf_page"] - 1
            if rotation:
                original[n].set_rotation((original[n].rotation + rotation) % 360)
            if original[n].get_pixmap().digest != derived[n].get_pixmap().digest:
                raise ValueError("OCR changed visible page rendering")
    return reports


async def run(args):
    args.output.mkdir(parents=True, exist_ok=True)
    rotations = dict((item.split(":")[0], int(item.split(":")[1])) for item in args.rotate)
    if any(r not in {0, 90, 180, 270} for r in rotations.values()):
        raise ValueError("Only right-angle orientation corrections are supported")
    rows = []
    for path in sorted(args.inputs.glob("*.pdf")):
        pages = inspect(path)
        scanned = [p["pdf_page"] for p in pages if p["characters"] < 80 and p["has_images"]]
        rows.append({"id": path.stem, "source_sha256": sha(path), "page_count": len(pages),
                     "source_pages": pages, "ocr_pages": scanned, "rotation_correction": rotations.get(path.stem, 0)})
    if args.inspect_only:
        write(args.output / "preflight.json", rows)
        print(json.dumps({"documents": len(rows), "need_ocr_documents": sum(bool(r["ocr_pages"]) for r in rows),
                          "need_ocr_pages": sum(len(r["ocr_pages"]) for r in rows)}))
        return
    for row in rows:
        source = args.inputs / (row["id"] + ".pdf")
        target = args.output / (row["id"] + "-ocr.pdf")
        receipt = args.output / (row["id"] + "-ocr.json")
        if row["ocr_pages"]:
            if receipt.exists() and target.exists():
                previous = json.loads(receipt.read_text(encoding="utf-8"))
                if (previous["source_sha256"] != row["source_sha256"] or previous["import_sha256"] != sha(target)
                        or previous.get("rotation_correction", 0) != row["rotation_correction"]):
                    raise ValueError("Existing OCR receipt identity differs")
                row.update(previous)
            else:
                if target.exists():
                    raise FileExistsError("Unverified derivative already exists")
                row["ocr_result"] = await ocr_derivative(source, target, row["source_pages"], row["rotation_correction"])
                if sha(source) != row["source_sha256"]:
                    raise ValueError("Original PDF changed")
                row.update(import_sha256=sha(target), preprocessing="external_windows_ocr_en-US",
                           visible_page_rendering_unchanged=not bool(row["rotation_correction"]),
                           rendering_matches_original_after_declared_rotation=True,
                           created_at=datetime.now(timezone.utc).isoformat(),
                           import_pages=inspect(target), human_ocr_review="pending")
                write(receipt, row)
        else:
            row.update(import_sha256=row["source_sha256"], preprocessing="none", import_pages=row["source_pages"])
    write(args.output / "preparation.json", rows)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inputs", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--inspect-only", action="store_true")
    parser.add_argument("--rotate", action="append", default=[], help="Explicit ID:degrees correction, e.g. HU20:270")
    asyncio.run(run(parser.parse_args()))
